#!/usr/bin/env node
/**
 * Writes .env.local for the LOCAL Supabase stack, reading the URL and keys
 * from `supabase status`. These local keys are the stack's development
 * defaults, not production secrets. Never point this at a cloud project.
 *
 * Usage: npm run env:local   (after `npx supabase start`)
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const output = execFileSync('npx', ['supabase', 'status', '-o', 'env'], {
  encoding: 'utf8',
  shell: process.platform === 'win32',
});

const values = Object.fromEntries(
  output
    .split(/\r?\n/)
    .map((line) => /^([A-Z_]+)="?(.*?)"?$/.exec(line.trim()))
    .filter(Boolean)
    .map(([, key, value]) => [key, value]),
);

const required = ['API_URL', 'PUBLISHABLE_KEY', 'SECRET_KEY'];
const missing = required.filter((key) => !values[key]);
if (missing.length > 0) {
  console.error(`supabase status did not report: ${missing.join(', ')}. Is it running?`);
  process.exit(1);
}

const siteUrl = process.env.SITE_URL ?? 'http://localhost:3000';
const contents = `# Generated by scripts/write-env-local.mjs for the LOCAL Supabase stack.
# Local development keys only. Do not commit (.gitignore covers this file).
NEXT_PUBLIC_SUPABASE_URL=${values.API_URL}
NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${values.PUBLISHABLE_KEY}
SUPABASE_SECRET_KEY=${values.SECRET_KEY}
NEXT_PUBLIC_SITE_URL=${siteUrl}
`;

writeFileSync('.env.local', contents);
console.log(`Wrote .env.local (Supabase at ${values.API_URL}, site ${siteUrl}).`);
